export function getUGProgrammeBySlug(slug) {
  if (!slug) return null;
  const clean = String(slug).toLowerCase().replace(/[^a-z0-9-]/g, '').trim();
  return UG_PROGRAMMES_CATALOGUE.find(p => p.slug === clean || p.id === clean || p.code.toLowerCase() === clean) || null;
}
