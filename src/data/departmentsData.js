// Helper to get department by ID or slug
export function getDepartmentById(idOrSlug) {
  if (!idOrSlug) return null;
  const clean = String(idOrSlug).trim().toLowerCase().replace(/[^a-z0-9-]/g, '');
  
  return DEPARTMENTS.find(d => {
    const dId = d.id.toLowerCase();
    const dSlug = d.slug.toLowerCase();
    return dId === clean || dSlug === clean || ('dept_' + dId) === clean || dId === clean.replace('dept_', '');
  }) || null;
}
